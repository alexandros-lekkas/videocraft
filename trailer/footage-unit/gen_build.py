"""A set built on camera, layer by layer: writes trailer/footage-unit/build-<set>.toml from the set's own commands.

    python3 trailer/footage-unit/gen_build.py barn-stage

The set is compiled as `[[world.set]]` would expand it. Every command that lies inside the build box (the building,
not the yard or the hills) is held back from staging; fills are split into one fill per block layer, and each layer
becomes one timed `command` cue, bottom to top, so the building rises in the shot. Within a layer the commands keep
their order, and layers never overlap, so the finished set is exactly the set (later fills still win).
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SPECS = {
    'barn-stage': {
        'box': (-15, 228, -12, 15, 250, 12),          # x1 y1 z1 x2 y2 z2, world blocks (set at [0, 230, 0])
        'time': 11000,
        'duration': 11.0,
        'start': 0.6,
        'span': 8.4,
        'camera': '{ rig = "orbit", center = [0.5, 234, 0.5], look = [0.5, 235.0, 0.5], radius = 31, height = 15, '
                  'from = 200, sweep = 40, ease = "linear", fov = 60 }',
    },
}


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def compile_set(name):
    with tempfile.TemporaryDirectory() as d:
        probe = Path(d) / 'probe.toml'
        probe.write_text(f'name = "probe"\n[world]\nseed = "videocraft"\n[[world.set]]\nname = {q(name)}\n'
                         'at = [0, 230, 0]\n[[shot]]\nname = "x"\nduration = 1.0\n'
                         'camera = { rig = "fixed", eye = [0, 260, 40], at = [0, 232, 0] }\n', encoding='utf-8')
        p = subprocess.run([str(ROOT / 'bin' / 'videocraft'), 'compile', str(probe)], cwd=ROOT,
                           capture_output=True, text=True, check=True)
    return json.loads(p.stdout[p.stdout.index('{'):])['plan']['world']['stage'][0]


def split(cmd, box):
    """None if the command stays in staging, else [(layer y, command)]."""
    x1, y1, z1, x2, y2, z2 = box
    w = cmd.split()
    inside = lambda ax, az, bx, bz: x1 <= ax and bx <= x2 and z1 <= az and bz <= z2
    if w[0] == 'fill':
        a = [int(v) for v in w[1:7]]
        lo, hi = min(a[1], a[4]), max(a[1], a[4])
        if not inside(min(a[0], a[3]), min(a[2], a[5]), max(a[0], a[3]), max(a[2], a[5])) or hi < y1:
            return None
        rest = ' '.join(w[7:])
        return [(y, f'fill {a[0]} {y} {a[2]} {a[3]} {y} {a[5]} {rest}') for y in range(lo, hi + 1)]
    if w[0] == 'setblock':
        x, y, z = (int(v) for v in w[1:4])
        return [(y, cmd)] if inside(x, z, x, z) and y >= y1 else None
    if w[0] == 'summon':
        x, y, z = (float(v) for v in w[2:5])
        return [(int(y // 1), cmd)] if inside(x, z, x, z) and y >= y1 else None
    return None


def main(name):
    spec = SPECS[name]
    stage = compile_set(name)
    staged, layers = [], {}
    for c in stage['commands']:
        parts = split(c, spec['box'])
        if parts is None:
            staged.append(c)
        else:
            for y, cc in parts:
                layers.setdefault(y, []).append(cc)
    ys = sorted(layers)
    # Time is shared out by weight: every command one unit, every layer `pause` more, so a busy layer goes up block by
    # block (its commands in their order, a few to a cue) and the thin roof layers follow each other steadily.
    pause = spec.get('pause', 14)
    total = sum(len(layers[y]) + pause for y in ys)
    unit = spec['span'] / total
    cues, t = [], spec['start']
    for y in ys:
        n = len(layers[y])
        per = max(1, round(n / max(1, (n * unit) * 60 / spec.get('frames', 2))))
        for i in range(0, n, per):
            cues.append((t + i * unit, layers[y][i:i + per]))
        t += (n + pause) * unit
    out = [f'# Generated by trailer/footage-unit/gen_build.py: the {name} set rising layer by layer.',
           f'# {len(stage["commands"])} set commands; {len(staged)} staged (the yard and hills), '
           f'{sum(map(len, layers.values()))} in {len(ys)} timed layers.',
           f'#   bin/videocraft run trailer/footage-unit/build-{name}.toml',
           f'name = "fu-build-{name}"', 'seed = 3', f'description = "The {name} set built on camera, layer by layer"',
           '', '[world]', 'seed = "videocraft"', f'time = {spec["time"]}', '', '[[world.stage]]', 'do = "command"',
           f'forceload = {json.dumps(stage["forceload"])}', 'commands = [']
    out += [f'  {q(c)},' for c in staged] + [']', '', '[[shot]]', 'name = "build"', f'duration = {spec["duration"]}',
                                             f'camera = {spec["camera"]}']
    for at, cs in cues:
        out += ['', '[[shot.cue]]', f'at = {at:.3f}', 'do = "command"', 'commands = [']
        out += [f'  {q(c)},' for c in cs] + [']']
    path = ROOT / 'trailer' / 'footage-unit' / f'build-{name}.toml'
    path.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{path.relative_to(ROOT)}: {len(staged)} staged, {len(ys)} layers '
          f'({", ".join(f"{y}:{len(layers[y])}" for y in ys)})')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'barn-stage')
