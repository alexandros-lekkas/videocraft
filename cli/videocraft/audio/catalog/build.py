"""`videocraft audio catalog --refresh`: writes minecraft.toml (every sound event) and music.toml (every music track)
from the local game assets and curated.toml. Names, ids, variant counts, lengths, tags and measurements only: no audio
is written into the repository, ever (the user's own game install is where the sounds stay; docs/SOUNDS.md).

Lengths come from each Ogg file's own header (the last page's granule position over the sample rate), so the refresh
reads a few kilobytes per sound, not the audio. Music is decoded through ffmpeg into memory and measured (musicfeat.py).
"""
import statistics
import struct
import time
import tomllib

from videocraft.audio import assets
from videocraft.audio import library
from videocraft.audio.catalog import HERE, rules, tomlw

HEADER = """# The Minecraft sound catalog: every sound event of the game, by id, with what it means. GENERATED by
# `videocraft audio catalog --refresh` from the local game assets ({index}) and curated.toml; edit curated.toml
# (or catalog/rules.py) and refresh, not this file. No audio is in the repository: the mix reads the sounds from your
# own game install at export time, and an original-only export swaps each one for its `original` library stand-in.
#
# [events] "<id>" = {{ category, variants, seconds, min, max, tags, original }}
#   category  the sound category the game usually plays it in (from the id; sounds.json does not say)
#   variants  how many sound files the event picks from; seconds: their median length (min, max when they differ)
#   tags      words a script can ask for (`tag = "pop"`), from rules.py and curated meanings
#   original  the original library sound (library/library.toml) that stands in for it, when there is a good one
# [best]      per tag, the events preferred in order
# [palette.*] the comedy palette (docs/SOUNDS.md)
"""

MUSIC_HEADER = """# The Minecraft music map: every music track of the game. GENERATED by `videocraft audio catalog --refresh` from the
# local game assets ({index}) and curated.toml (moods, vocals, notes). Lengths, tempo, levels, starts and loops are
# MEASURED on the decoded audio (catalog/musicfeat.py; ffmpeg decodes, the standard library measures); moods are
# hand-assigned in curated.toml (mood_by = "hand") or, for a track it does not list, guessed from the measurements
# (mood_by = "measured"). No audio is in the repository: the mix reads tracks from your own game install.
#
# [track."<file>"]
#   events        the music events that play it (music.game, music.overworld.meadow, music_disc.cat, …)
#   seconds       length;  mood: first is the main one;  vocals: sung lyrics
#   bpm           the strongest pulse of the onset envelope, 60-180;  pulse: its strength (autocorrelation, 0-1),
#                 steady >= 0.3, loose 0.15-0.3, free below (ambient tracks: treat bpm as a hint)
#   level_db      median 1 s RMS level (dBFS);  dynamics_db: p90 - p10 of the 1 s levels;  bright_db: high band (>1.5 kHz)
#                 against the whole, lower is darker;  onsets_per_s: density of note attacks
#   entry         seconds: the first downbeat after the intro (the level within 3 dB of its median, snapped to the
#                 strongest onset nearby): the default `start` when a script picks the track by mood
#   energetic     [[start, end], …] the most energetic 8 s windows (level plus onset density), best first
#   loops         [[a, b, score_db], …] a jump from b back to a that matches in level and brightness over 2 s
#                 (score: mean dB difference, lower is better; a whole number of beats when the pulse is steady)
#   quiet_end     seconds where the track's last loud passage ends
"""


def ogg_seconds(path):
    """Length of an Ogg Vorbis file from its headers: last granule position / sample rate. None if unreadable."""
    try:
        with open(path, 'rb') as f:
            head = f.read(4096)
            f.seek(0, 2)
            size = f.tell()
            f.seek(max(0, size - 65536))
            tail = f.read()
    except OSError:
        return None
    i = head.find(b'\x01vorbis')
    if i < 0:
        return None
    rate = struct.unpack_from('<I', head, i + 12)[0]
    j = tail.rfind(b'OggS')
    if j < 0 or rate <= 0 or j + 14 > len(tail):
        return None
    granule = struct.unpack_from('<q', tail, j + 6)[0]
    return granule / rate if granule > 0 else None


def file_seconds(file):
    try:
        return ogg_seconds(assets.object_path(assets.sound_key(file)))
    except assets.MissingAssets:
        return None


def curated():
    return tomllib.loads((HERE / 'curated.toml').read_text())


def build_events(say=print):
    sounds = assets.sounds_json()
    cur = curated()
    lib = library.index()
    events = {}
    lengths = {}
    for name in sorted(sounds):
        files = assets.event_files(name)
        secs = []
        for f in files:
            if f not in lengths:
                lengths[f] = file_seconds(f)
            if lengths[f] is not None:
                secs.append(lengths[f])
        tags = rules.tags_for(name)
        row = {'category': rules.category_of(name), 'variants': len(files)}
        if secs:
            row['seconds'] = round(statistics.median(secs), 3)
            if max(secs) - min(secs) > 0.05:
                row['min'], row['max'] = round(min(secs), 3), round(max(secs), 3)
        row['tags'] = tags
        if not name.startswith('music'):
            original = rules.original_for(name, tags, lib)
            if original:
                row['original'] = original
        events[name] = row
    # Palette names are tags of the events they use, and the [best] lists put their events first.
    best = {k: [e for e in v if e in events] for k, v in cur.get('best', {}).items()}
    for tag, ids in best.items():
        for e in ids:
            if tag not in events[e]['tags']:
                events[e]['tags'] = sorted(set(events[e]['tags']) | {tag})
    # A mob's name alone means its ambient voice first, then its other voices.
    for name in events:
        parts = name.split('.')
        if parts[0] == 'entity' and len(parts) == 3 and parts[2] == 'ambient' and parts[1] not in rules.NOT_MOBS:
            mob = parts[1]
            if mob not in best:
                voices = [f'entity.{mob}.{a}' for a in ('ambient', 'hurt', 'death') if f'entity.{mob}.{a}' in events]
                best[mob] = voices
    palette = {}
    for pname, p in cur.get('palette', {}).items():
        missing = [s['id'] for s in _palette_steps(p) if s['id'] not in events]
        if missing:
            say(f'palette.{pname}: not in this game version, left out: {", ".join(missing)}')
        if p.get('original') and p['original'] not in lib:
            raise SystemExit(f'curated.toml palette.{pname}: original = "{p["original"]}" is not in library/library.toml')
        palette[pname] = _palette_without(p, set(missing))
        steps = _palette_steps(palette[pname])
        for s in steps:
            events[s['id']]['tags'] = sorted(set(events[s['id']]['tags']) | {pname})
        if steps and pname not in best:
            best[pname] = list(dict.fromkeys(s['id'] for s in steps))
    return events, best, palette, len(lengths)


def _palette_steps(p):
    steps = list(p.get('pick', [])) + list(p.get('sequence', []))
    if 'roll' in p:
        steps.append({'id': p['roll']['id']})
        steps += list(p['roll'].get('end', []))
    return steps


def _palette_without(p, missing):
    out = dict(p)
    for k in ('pick', 'sequence'):
        if k in out:
            out[k] = [s for s in out[k] if s['id'] not in missing]
    if 'roll' in out:
        roll = dict(out['roll'])
        if roll['id'] in missing:
            del out['roll']
        else:
            roll['end'] = [s for s in roll.get('end', []) if s['id'] not in missing]
            out['roll'] = roll
    return out


def write_events(events, best, palette):
    path = HERE / 'minecraft.toml'
    text = [HEADER.format(index=assets.index_file().name)]
    text.append(tomlw.inline_rows('events', events))
    text.append(tomlw.table('best', best))
    for name in sorted(palette):
        p = palette[name]
        fields = {k: p[k] for k in ('about', 'original', 'pick', 'sequence', 'roll') if k in p}
        text.append(tomlw.table(f'palette.{tomlw.key(name)}', fields))
    path.write_text('\n'.join(text))
    tomllib.loads(path.read_text())  # it must read back
    return path


def build_music(say=print):
    from videocraft.audio.catalog import musicfeat
    sounds = assets.sounds_json()
    cur = curated().get('music', {})
    events_of = {}
    for name in sorted(sounds):
        if name.startswith('music'):
            for f in assets.event_files(name):
                events_of.setdefault(f, []).append(name)
    files = sorted(k[len('minecraft/sounds/'):-len('.ogg')] for k in assets.objects()
                   if k.startswith('minecraft/sounds/') and k.endswith('.ogg') and ('/music/' in k or '/records/' in k))
    tracks = {}
    for i, f in enumerate(files):
        started = time.time()
        feat = musicfeat.measure(assets.object_path(assets.sound_key(f)))
        c = cur.get(f, {})
        mood = c.get('mood') or musicfeat.guess_mood(feat)
        row = {'events': events_of.get(f, []), 'seconds': round(ogg_seconds(assets.object_path(assets.sound_key(f))) or feat['seconds'], 2),
               'mood': mood, 'mood_by': 'hand' if c.get('mood') else 'measured'}
        if c.get('vocals'):
            row['vocals'] = True
        if c.get('bed') is False:
            row['bed'] = False
        row.update({k: feat[k] for k in ('bpm', 'pulse', 'level_db', 'dynamics_db', 'bright_db', 'onsets_per_s', 'entry', 'energetic',
                                         'loops', 'quiet_end')})
        if c.get('note'):
            row['note'] = c['note']
        tracks[f] = row
        say(f'[{i + 1:2d}/{len(files)}] {f:48} {row["seconds"]:6.1f} s  {feat["bpm"]:5.1f} bpm pulse {feat["pulse"]:.2f}  '
            f'entry {feat["entry"]:5.1f} s  {"/".join(mood)}  ({time.time() - started:.1f} s)')
    return tracks


def write_music(tracks):
    path = HERE / 'music.toml'
    text = [MUSIC_HEADER.format(index=assets.index_file().name)]
    for f, row in tracks.items():
        text.append(tomlw.table(f'track.{tomlw.key(f)}', row))
    path.write_text('\n'.join(text))
    tomllib.loads(path.read_text())
    return path


def refresh(music=True, say=print):
    """Rebuilds the catalogs from the local game assets; returns the paths written."""
    assets.index_file()
    started = time.time()
    events, best, palette, files = build_events(say)
    out = [write_events(events, best, palette)]
    tagged = sum(1 for e in events.values() if e.get('original'))
    say(f'EVENTS   {len(events)} events, {files} sound files measured, {tagged} with an original stand-in, {len(palette)} palette '
        f'entries -> {out[0]} ({time.time() - started:.1f} s)')
    if music:
        tracks = build_music(say)
        out.append(write_music(tracks))
        say(f'MUSIC    {len(tracks)} tracks -> {out[1]} ({time.time() - started:.1f} s)')
    return out
